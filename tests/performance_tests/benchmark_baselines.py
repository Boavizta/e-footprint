"""Baseline benchmarks of the computation engine on the big-system fixture.

Run as a script to measure the reference numbers and write them to baseline_results.json
(committed): full eager build (cold first-in-process build + warm rebuild average), peak RSS after
build, single in-memory edits, load-to-ready from the canonical fixture,
deserialize-edit-reserialize round-trip, the nudge-one-input /
read-one-target loop, and the serialized fixture weight. Engine changes are evaluated by re-running
this script and diffing against the committed reference file. The committed reference was recorded
on the eager push engine right before the pull-based overhaul: tests/performance_tests/test_perf_gates.py
diffs the pull engine against it.

Requires the fixtures generated by `python tests/performance_tests/generate_big_system.py`.

Usage:
    PYTHONPATH=./ python tests/performance_tests/benchmark_baselines.py [--nudge-iterations N]
"""
import argparse
import gc
import json
import os
import platform
import resource
import sys
from datetime import datetime, timezone
from statistics import mean
from time import perf_counter

import efootprint
from efootprint.abstract_modeling_classes.source_objects import SourceValue
from efootprint.api_utils.json_to_system import json_to_system
from efootprint.constants.units import u
from efootprint.logger import logger
from tests.performance_tests.generate_big_system import (
    BIG_SYSTEM_STANDARD_PARAMS, BIG_SYSTEM_FIXTURE, form_inputs_hourly_starts, generate_big_system, root_dir)
from tests.performance_tests.test_big_system_from_and_to_json_performance import update_on_system

BASELINE_RESULTS_FILEPATH = os.path.join(root_dir, "baseline_results.json")


def peak_rss_mb():
    ru_maxrss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return round(ru_maxrss / 1e6 if sys.platform == "darwin" else ru_maxrss / 1e3, 1)


def pick_edited_job(system):
    return list(list(system.usage_patterns[0].usage_journey.uj_steps)[0].jobs)[1]


def timed_full_build():
    start = perf_counter()
    system = generate_big_system(**BIG_SYSTEM_STANDARD_PARAMS)
    return system, perf_counter() - start


def benchmark_scalar_edit_ms(system, nb_iterations=10):
    job = pick_edited_job(system)
    durations = []
    for i in range(nb_iterations):
        new_value = SourceValue((100 if i % 2 == 0 else 30) * u.MB)
        start = perf_counter()
        job.data_transferred = new_value
        durations.append(perf_counter() - start)
    return round(1000 * mean(durations), 1)


def benchmark_timeseries_edit_ms(system, nb_iterations=6):
    durations = []
    for i in range(nb_iterations):
        new_value = form_inputs_hourly_starts(
            BIG_SYSTEM_STANDARD_PARAMS["nb_years"], initial_volume=2000 if i % 2 == 0 else 3000)
        start = perf_counter()
        system.usage_patterns[0].hourly_usage_journey_starts = new_value
        durations.append(perf_counter() - start)
    return round(1000 * mean(durations), 1)


def benchmark_nudge_and_read_loop(system, nb_iterations):
    """Nudge one input then read one target value, in a tight loop on the in-memory model."""
    job = pick_edited_job(system)
    start = perf_counter()
    for i in range(nb_iterations):
        job.data_transferred = SourceValue((100 if i % 2 == 0 else 30) * u.MB)
        float(system.total_footprint.sum().magnitude)
    total_seconds = perf_counter() - start
    avg_ms = 1000 * total_seconds / nb_iterations
    return {"iterations": nb_iterations, "avg_ms_per_iteration": round(avg_ms, 1),
            "projected_1000_iterations_seconds": round(avg_ms, 1)}


def benchmark_load_to_ready(nb_iterations=5):
    """Parse the canonical fixture and rebuild a ready-to-use system, no recomputation."""
    parse_durations, build_durations = [], []
    for _ in range(nb_iterations):
        start = perf_counter()
        with open(BIG_SYSTEM_FIXTURE) as file:
            system_dict = json.load(file)
        parse_durations.append(perf_counter() - start)
        start = perf_counter()
        json_to_system(system_dict)
        build_durations.append(perf_counter() - start)
    json_parse_avg_ms = round(1000 * mean(parse_durations), 1)
    json_to_system_avg_ms = round(1000 * mean(build_durations), 1)
    return {"json_parse_avg_ms": json_parse_avg_ms, "json_to_system_avg_ms": json_to_system_avg_ms,
            "total_avg_ms": round(json_parse_avg_ms + json_to_system_avg_ms, 1)}


def run_benchmarks(nudge_iterations, nb_warm_builds=2):
    results = {}
    system, cold_build_seconds = timed_full_build()
    # Snapshot peak RSS right after the first build so warm rebuilds can't inflate the metric.
    peak_rss_after_build_mb = peak_rss_mb()
    warm_build_durations = []
    for _ in range(nb_warm_builds):
        del system
        gc.collect()
        system, duration = timed_full_build()
        warm_build_durations.append(duration)
    results["full_build"] = {
        "cold_seconds": round(cold_build_seconds, 3),
        "warm_avg_seconds": round(mean(warm_build_durations), 3)}
    results["peak_rss_after_build_mb"] = peak_rss_after_build_mb
    results["scalar_edit_avg_ms"] = benchmark_scalar_edit_ms(system)
    results["timeseries_edit_avg_ms"] = benchmark_timeseries_edit_ms(system)
    results["nudge_and_read_loop"] = benchmark_nudge_and_read_loop(system, nudge_iterations)
    del system

    results["load_to_ready"] = benchmark_load_to_ready()
    with open(BIG_SYSTEM_FIXTURE) as file:
        system_dict = json.load(file)
    results["load_edit_save_avg_ms"] = update_on_system(
        5, system_dict, "Job", "data_transferred", SourceValue(100 * u.MB))
    results["canonical_json_bytes"] = os.path.getsize(BIG_SYSTEM_FIXTURE)

    return {
        "recorded_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "platform": platform.platform(),
        "machine": platform.machine(),
        "python_version": platform.python_version(),
        "efootprint_version": efootprint.__version__,
        "fixture_params": BIG_SYSTEM_STANDARD_PARAMS,
        "results": results,
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nudge-iterations", type=int, default=1000)
    args = parser.parse_args()

    baseline = run_benchmarks(args.nudge_iterations)
    with open(BASELINE_RESULTS_FILEPATH, "w") as file:
        file.write(json.dumps(baseline, indent=4) + "\n")
    logger.info(f"Baseline results written to {BASELINE_RESULTS_FILEPATH}")
    print(json.dumps(baseline, indent=4))
